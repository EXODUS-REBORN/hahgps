package ru.hahgps.util;

/** Как рисовать стрелку направления в BossBar. */
public enum ArrowStyle {

    /** Глифы, если клиент подтвердил загрузку ресурспака, иначе ванильный символ. */
    AUTO,

    /** Всегда рисованный глиф из ресурспака {@code hahgps:arrow}. */
    GLYPHS,

    /** Всегда ванильный символ: работает без пака. */
    UNICODE
}
